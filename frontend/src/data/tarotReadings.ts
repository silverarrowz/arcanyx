export type MinorSuit = "wands" | "cups" | "swords" | "pentacles";

export type SuitTheme = {
  suit: MinorSuit;
  element: "fire" | "water" | "air" | "earth";
  title: string;
  tint: string;
  border: string;
  glow: string;
};

