function major(
  id: string,
  name: string,
  nameRu: string,
  symbol: string,
  short: string,
  detailed: string,
  gradient: [string, string],
): TarotCard {
  return { id, name, nameRu, symbol, short, detailed, gradient };
}

function minor(
  suitId: string,
  suitEn: string,
  suitRu: string,
  valueId: string,
  valueEn: string,
  valueRu: string,
  symbol: string,
  short: string,
): TarotCard {
  const detailed =
    MINOR_DESCRIPTIONS[suitId]?.[valueId] ??
    `${short} ${SUIT_THEMES[suitId]} Эта карта советует смотреть на ситуацию честно: где энергия уже течёт свободно, а где ты удерживаешь её страхом или привычкой.`;
  return {
    id: `${valueId}-of-${suitId}`,
    name: `${valueEn} of ${suitEn}`,
    nameRu: `${valueRu} ${suitRu}`,
    symbol,
    short,
    detailed,
    gradient: SUIT_GRADIENTS[suitId],
  };
}

